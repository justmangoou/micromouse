"""Export a fixed static block layout (and reference planner numbers) for the firmware.

    python -m sim.course.export_map

Writes firmware/include/map_data.h (the map the car stores after run 1) and
firmware/test/test_nav/ref_data.h (what the Python planner produces on it, for the host tests).
The blocks are the official map (config.STATIC_BLOCKS).
"""
from pathlib import Path

import numpy as np

from .env import MicromouseEnv
from .planner import AStarDriver

ROOT = Path(__file__).resolve().parents[2] / "firmware"


def main():
    env = MicromouseEnv(with_random=False)
    env.reset(1)
    centers, angles = env.centers0, env.angles
    rows = ",\n".join(f"    {{{c[0]:.2f}f, {c[1]:.2f}f, {a:.4f}f}}" for c, a in zip(centers, angles))
    (ROOT / "include").mkdir(parents=True, exist_ok=True)
    (ROOT / "include" / "map_data.h").write_text(
        "// Generated by `python -m sim.course.export_map`. Static blocks mapped in run 1: x, y (cm), angle (rad).\n"
        "#pragma once\n\n"
        f"constexpr int MAP_BLOCK_COUNT = {len(centers)};\n"
        f"constexpr float MAP_BLOCKS[MAP_BLOCK_COUNT][3] = {{\n{rows}\n}};\n"
    )

    driver = AStarDriver()
    driver.reset(env)
    path_len = float(driver.path_s[-1])
    (ROOT / "test" / "test_nav").mkdir(parents=True, exist_ok=True)
    (ROOT / "test" / "test_nav" / "ref_data.h").write_text(
        "// Generated by `python -m sim.course.export_map`: what sim/course/planner.py plans on MAP_BLOCKS.\n"
        "#pragma once\n\n"
        f"constexpr float REF_PATH_LENGTH = {path_len:.2f}f;  // cm, including the 30 cm run-through\n"
        f"constexpr int REF_PATH_POINTS = {len(driver.path)};\n"
    )
    print(f"{len(centers)} blocks, reference path {path_len:.1f} cm, {len(driver.path)} points")


if __name__ == "__main__":
    main()
