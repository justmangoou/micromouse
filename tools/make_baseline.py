"""Build the ToF baseline for random-block detection from clean runs (no random block, T14 in its right place).

    python3 tools/make_baseline.py data/clean_runs/*.csv > include/baseline.h
    python3 tools/make_baseline.py --bin base.bin data/clean_runs/*.csv      # for tools/replay_run

Each input is a fast-log CSV (tools/read_run.py --csv). The car follows the same path every run, so for every pose cell
(x, y 30 mm; heading 0.15 rad) on the right-wing part of the route the baseline keeps the SHORTEST range each sensor read in
any clean run. The firmware flags a block when a reading is far shorter than that: static things the map does not have (the
pit corner, T14's real position, walls) are in the baseline and cancel out, a new block on the path is not.
Entry: cell x, cell y, heading bin, then the three ranges in 5 mm units (255 = no target): nav::BaselineEntry.
"""
import csv, math, struct, sys

CELL, BIN, XMIN = 30.0, 0.15, 800.0


def build(paths):
    cells = {}
    for p in paths:
        for r in csv.DictReader(open(p)):
            x, y, th = float(r["x"]), float(r["y"]), float(r["th_mrad"]) / 1000.0
            if x < XMIN:
                continue
            key = (round(x / CELL), round(y / CELL), round(th / BIN))
            rng = [min(255, int(r[k]) // 5) for k in ("tofR", "tofF", "tofL")]
            cells[key] = rng if key not in cells else [min(a, b) for a, b in zip(cells[key], rng)]
    return cells


def main(argv):
    out_bin = None
    if argv and argv[0] == "--bin":
        out_bin, argv = argv[1], argv[2:]
    cells = build(argv)
    entries = sorted(cells.items())
    if out_bin:
        with open(out_bin, "wb") as f:
            for (cx, cy, b), rng in entries:
                f.write(struct.pack("<hhbBBB", cx, cy, b, *rng))
        return
    print("// Generated by tools/make_baseline.py from %d clean run(s): %s" % (len(argv), ", ".join(a.split("/")[-1] for a in argv)))
    print("// %d entries. Do not edit: regenerate (see the tool) when the course or the clean runs change." % len(entries))
    print("#pragma once\n#include \"navigator.h\"\n")
    print("constexpr float BASE_CELL = %.1ff, BASE_BIN = %.2ff;" % (CELL, BIN))
    print("constexpr int BASE_N = %d;" % len(entries))
    print("constexpr nav::BaselineEntry BASE_TABLE[BASE_N] = {")
    for (cx, cy, b), rng in entries:
        print("    {%d, %d, %d, {%d, %d, %d}}," % (cx, cy, b, *rng))
    print("};")


if __name__ == "__main__":
    main(sys.argv[1:])
