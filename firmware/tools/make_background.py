"""Build include/background.h: where the ToF sensors return hits on a run with NO random block that the map does not explain.

    for r in data/clean_runs/*.csv; do /tmp/replay_run $r 0 d | grep ^HIT; done | python3 tools/make_background.py > include/background.h

(build tools/replay_run.cpp first, see its header). Each HIT,x,y,sensor line is the world position of an unexplained
reading on a clean run. The right wing (x 1100..1820) is a 40 mm grid; every cell with a hit is marked and dilated by one cell.
The Navigator treats a reading whose hit point is on a marked cell as background (the pit corner, wall returns, anything
static the map does not have) and never as a random block. Add more clean runs and regenerate if a phantom shows up.
"""
import sys

X0, Y0, CELL = 1100.0, -200.0, 40.0
NX, NY = 18, 35  # x 1100..1820, y -200..1200


def main():
    marked = set()
    n = 0
    for line in sys.stdin:
        if not line.startswith("HIT,"):
            continue
        _, x, y, _k = line.strip().split(",")
        n += 1
        ix, iy = int((float(x) - X0) // CELL), int((float(y) - Y0) // CELL)
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if 0 <= ix + dx < NX and 0 <= iy + dy < NY:
                    marked.add((ix + dx, iy + dy))
    bits = bytearray((NX * NY + 7) // 8)
    for ix, iy in marked:
        i = iy * NX + ix
        bits[i >> 3] |= 1 << (i & 7)
    print("// Generated by tools/make_background.py from %d unexplained hits on clean runs; %d of %d cells marked." % (n, len(marked), NX * NY))
    print("#pragma once\n#include <stdint.h>\n")
    print("constexpr float BG_X0 = %.1ff, BG_Y0 = %.1ff, BG_CELL = %.1ff;" % (X0, Y0, CELL))
    print("constexpr int BG_NX = %d, BG_NY = %d;" % (NX, NY))
    print("constexpr uint8_t BG_BITS[%d] = {" % len(bits))
    for i in range(0, len(bits), 12):
        print("    " + ", ".join("0x%02X" % b for b in bits[i:i + 12]) + ",")
    print("};")


if __name__ == "__main__":
    main()
